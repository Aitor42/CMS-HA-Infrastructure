// generatedSitePP maps every configured node to its role by exact certname.
// The committed site.pp uses hostname regexes (`/^internal-master/`), so a
// renamed node silently fell through to role::base.
func (p *Phase) generatedSitePP() ([]byte, error) {
	type entry struct {
		certname string
		role     string
		params   map[string]string
	}
	var entries []entry

	add := func(n config.NodeDetail, role string, params map[string]string) {
		certname := strings.TrimSpace(n.FQDN)
		if certname == "" {
			certname = strings.TrimSpace(n.Name)
		}
		if certname == "" || n.IP == "" {
			return
		}
		entries = append(entries, entry{certname: certname, role: role, params: params})
	}

	add(p.cfg.Nodes.Jumpstart, "role::jumpstart", nil)
	add(p.cfg.Nodes.Router, "role::router", nil)
	for _, n := range p.cfg.Nodes.Masters {
		add(n, "role::k3s_master", nil)
	}
	for _, n := range p.cfg.Nodes.Workers {
		add(n, "role::k3s_worker", nil)
	}
	add(p.cfg.Nodes.Storage, "role::storage", nil)
	add(p.cfg.Nodes.Monitor, "role::monitor", nil)
	for _, n := range p.cfg.Nodes.CMSFrontends {
		add(n, "role::cms_frontend", nil)
	}

	// The first load balancer is the keepalived MASTER; deriving it from the
	// configured order keeps custom LB names working (the role used to compare
	// the hostname against the literal "main-lb1").
	var lbIPs []string
	for _, lb := range p.cfg.Nodes.LBs {
		if lb.IP != "" {
			lbIPs = append(lbIPs, lb.IP)
		}
	}
	for i, lb := range p.cfg.Nodes.LBs {
		params := map[string]string{
			"is_master": "true",
			"vip":       p.cfg.LBVIP(),
		}
		if i > 0 {
			params["is_master"] = "false"
		}
		if len(lbIPs) > 0 {
			params["master_ip"] = lbIPs[0]
		}
		if len(lbIPs) > 1 {
			params["backup_ip"] = lbIPs[1]
		}
		add(lb, "role::loadbalancer", params)
	}

	for _, n := range p.cfg.HotdeskSpecs() {
		detail := config.NodeDetail{Name: n.Name, IP: n.IP, FQDN: n.FQDN}
		add(detail, "role::hotdesk", nil)
	}

	var b strings.Builder
	b.WriteString("# Generated by `cms-ha phase setup-puppet` from config.yaml.\n")
	b.WriteString("# Do not edit: the next deployment overwrites this file.\n\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "node '%s' {\n", e.certname)
		if len(e.params) == 0 {
			fmt.Fprintf(&b, "  include %s\n", e.role)
		} else {
			fmt.Fprintf(&b, "  class { '%s':\n", e.role)
			keys := make([]string, 0, len(e.params))
			for k := range e.params {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, k := range keys {
				// is_master is declared as Boolean in role::loadbalancer; a
				// quoted 'true' is a String and Puppet rejects the class.
				if k == "is_master" {
					fmt.Fprintf(&b, "    %s => %s,\n", k, e.params[k])
					continue
				}
				fmt.Fprintf(&b, "    %s => '%s',\n", k, e.params[k])
			}
			b.WriteString("  }\n")
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("node default {\n  include role::base\n}\n")
	return []byte(b.String()), nil
}

// generatedHieraData is the config subset the manifests look up. Every value is
// rendered by yaml.Marshal so a domain or user name cannot break the file.
func (p *Phase) generatedHieraData() ([]byte, error) {
	if len(p.cfg.Nodes.CMSFrontends) == 0 {
		return nil, fmt.Errorf("nodes.cms_frontends must contain at least one frontend IP for NFS isolation")
	}
	frontendIPs := make([]string, 0, len(p.cfg.Nodes.CMSFrontends))
	seen := make(map[string]bool)
	for i, frontend := range p.cfg.Nodes.CMSFrontends {
		ip := net.ParseIP(frontend.IP)
		if ip == nil || ip.To4() == nil {
			return nil, fmt.Errorf("nodes.cms_frontends[%d].ip must be a valid IPv4 address for NFS isolation: %q", i, frontend.IP)
		}
		address := ip.To4().String()
		if !seen[address] {
			frontendIPs = append(frontendIPs, address)
			seen[address] = true
		}
	}
	data := map[string]any{
		"cms_ha::deploy_user":       p.cfg.SSHUser(),
		"cms_ha::jumpstart_ip":      p.cfg.Nodes.Jumpstart.IP,
		"cms_ha::jumpstart_ip_main": p.cfg.Nodes.Jumpstart.IPMain,
		"cms_ha::internal_cidr":     p.cfg.Network.Internal.CIDR,
		"cms_ha::main_cidr":         p.cfg.Network.Main.CIDR,
		"cms_ha::main_vip":          p.cfg.LBVIP(),
		"cms_ha::monitor_ip":        p.cfg.Nodes.Monitor.IP,
		"cms_ha::storage_ip":        p.cfg.Nodes.Storage.IP,
		"cms_ha::hosts_content":     p.hostsContent(),
		"cms_ha::cms_frontend_ips":  frontendIPs,
	}
	return yaml.Marshal(data)
}
